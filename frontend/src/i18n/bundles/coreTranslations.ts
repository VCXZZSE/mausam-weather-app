// UI string catalogue for Mausam.
//
// Keys are flat and dot-namespaced so `en` doubles as the key type: `hi` and
// `bn` are typed as Record<TranslationKey, string>, so TypeScript fails the
// build the moment a key is added to English without a Hindi/Bengali sibling.
//
// Only *static* interface copy lives here. Values that arrive from the weather
// API or the rules engine (condition names, AQI categories, advice sentences)
// are translated at render time by ./dynamicTranslations.

import {
  GENERATED_BRIEFING_BN,
  GENERATED_BRIEFING_EN,
  GENERATED_BRIEFING_HI,
} from "./generatedBriefing"
import { formatNumber } from "../numberFormat"

export type Language = "en" | "hi" | "bn"

export type LanguageOption = {
  code: Language
  /** Two-character code on the collapsed header trigger. */
  short: string
  /** Full endonym, shown in the dropdown and used for accessible names. */
  name: string
  /** Devanagari and Bengali script are both left-to-right, same as Latin. */
  dir: "ltr"
}

export const LANGUAGES: readonly LanguageOption[] = [
  { code: "en", short: "EN", name: "English", dir: "ltr" },
  { code: "hi", short: "हि", name: "हिन्दी", dir: "ltr" },
  { code: "bn", short: "বে", name: "বাংলা", dir: "ltr" },
] as const

export const DEFAULT_LANGUAGE: Language = "en"

export function isLanguage(value: unknown): value is Language {
  return LANGUAGES.some((option) => option.code === value)
}

